    <main>
        <p class="muted">Última actualización: 8 de junio de 2026</p>
        <p>CheckMedia Auditor ("la app") es una herramienta de uso interno operada por Efectimedios ("nosotros") para que auditores autorizados registren auditorías de espacios publicitarios en campo. Esta política describe qué datos tratamos y cómo.</p>

        <h2>1. Datos que recopilamos</h2>
        <ul>
            <li><strong>Credenciales de acceso:</strong> usuario y contraseña para autenticarte contra nuestro servidor. La contraseña no se almacena en el dispositivo.</li>
            <li><strong>Token de sesión:</strong> se guarda cifrado en el dispositivo para mantener tu sesión y permitir el desbloqueo biométrico.</li>
            <li><strong>Nombre del dispositivo:</strong> asociado al token de sesión para su gestión.</li>
            <li><strong>Datos de auditoría:</strong> código del espacio, criterios evaluados, observaciones, tipo y propósito de la visita, fecha/hora de captura.</li>
            <li><strong>Fotografías:</strong> imágenes que tomas como evidencia de la auditoría.</li>
        </ul>
        <p>No recopilamos ubicación GPS, contactos, ni datos de uso publicitario.</p>

        <h2>2. Cámara y fotos</h2>
        <p>La app usa la cámara únicamente para que captures fotos de evidencia de la auditoría en curso. Las fotos se redimensionan en el dispositivo y se envían a nuestro servidor asociadas a la auditoría. Sin conexión, se guardan localmente hasta sincronizarse.</p>

        <h2>3. Biometría</h2>
        <p>El desbloqueo por huella o rostro lo realiza el sistema operativo del dispositivo. La app nunca accede ni almacena tus datos biométricos; solo recibe la confirmación de que el desbloqueo fue exitoso para liberar la sesión guardada.</p>

        <h2>4. Cómo usamos los datos</h2>
        <p>Los datos de auditoría y las fotos se usan exclusivamente para registrar, revisar y reportar las inspecciones de espacios publicitarios dentro de la plataforma CheckMedia de Efectimedios.</p>

        <h2>5. Almacenamiento y seguridad</h2>
        <p>Los datos se transmiten por HTTPS a nuestros servidores. Las fotos se almacenan en la nube (Amazon S3). El token de sesión se guarda cifrado en el almacenamiento seguro del dispositivo.</p>

        <h2>6. Compartición con terceros</h2>
        <p>No vendemos ni compartimos tus datos con terceros para fines publicitarios. Solo se procesan a través de los proveedores de infraestructura necesarios para operar el servicio (alojamiento y almacenamiento en la nube).</p>

        <h2>7. Retención y eliminación</h2>
        <p>Los datos de auditoría se conservan mientras sean necesarios para la operación. Para solicitar la eliminación de tu cuenta o datos, contáctanos en el correo indicado abajo.</p>

        <h2>8. Uso autorizado</h2>
        <p>La app es de uso exclusivo para personal autorizado de Efectimedios y sus clientes. No está dirigida a menores de edad.</p>

        <h2>9. Cambios</h2>
        <p>Podemos actualizar esta política; publicaremos la versión vigente en esta misma dirección.</p>

